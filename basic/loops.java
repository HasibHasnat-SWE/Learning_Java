public class loops{
    public static void main(String[] args) {
        //FOR LOOP
        for(int i=0;i<10;i++){
            System.out.println("FOR loop: "+i);
        }
        //while loop
        int i=0;
        while(i<10){
            System.out.println("While Loop: "+ i);
            i++;
        }
        //do-while loop
        i=0;
        do { 
            System.out.println("Do Wile Loop: "+ i);
            i++;
        } while (i<10);
    }
}